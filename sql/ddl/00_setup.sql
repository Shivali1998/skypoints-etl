CREATE DATABASE IF NOT EXISTS SKYPOINTS;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.STAGING;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.CURATED;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.AUDIT;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.REF;
CREATE WAREHOUSE IF NOT EXISTS SKYPOINTS_WH WAREHOUSE_SIZE = 'LARGE' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

-- Whole line in $1 so the field count can be checked against the layout.
CREATE FILE FORMAT IF NOT EXISTS SKYPOINTS.RAW.FF_LINES
  TYPE = CSV FIELD_DELIMITER = NONE SKIP_BLANK_LINES = TRUE;
CREATE FILE FORMAT IF NOT EXISTS SKYPOINTS.RAW.FF_JSON TYPE = JSON STRIP_OUTER_ARRAY = TRUE;
CREATE STAGE IF NOT EXISTS SKYPOINTS.RAW.SKYPOINTS_STAGE;
